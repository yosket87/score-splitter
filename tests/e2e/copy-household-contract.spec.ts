import { test, expect } from '@playwright/test'
import { resetMockData } from './helpers'

test.beforeEach(async ({ page, request }) => {
  await resetMockData(request)
  await page.goto('/login')
  await page.getByRole('button', { name: 'パスワードでログイン', exact: true }).click()
  await page.getByPlaceholder('パスワード').fill('password')
  await page.getByRole('button', { name: 'ログイン', exact: true }).click()
  await page.waitForURL(/\/\d{4}\/\d{2}/)
})

for (const viewport of [{ width: 1280, height: 900 }, { width: 375, height: 812 }]) {
  test(`スキップ条件を確認し中断・再表示できる (${viewport.width}px)`, async ({ page }, testInfo) => {
    await page.setViewportSize(viewport)
    await page.goto('/2026/02')
    const trigger = page.getByRole('button', { name: /前月からコピー/ })
    if (viewport.width < 768) await expect(trigger).toHaveAttribute('data-slot', 'drawer-trigger')
    await trigger.click()
    const dialog = page.getByRole('dialog')
    const mode = dialog.getByRole('combobox', { name: '既存データの処理' })
    const description = dialog.getByText(/収入・支出はそれぞれ、コピー先の項目名と担当者/)
    await expect(description).not.toBeVisible()
    await mode.click()
    await page.getByRole('option', { name: /スキップ/ }).click()
    await expect(description).toBeVisible()
    await expect(mode).toHaveAccessibleDescription(/金額が違ってもスキップ/)
    await expect(description).toContainText('選んだ分をすべてコピー')
    await expect(description).toContainText('繰越は金額も同じ場合')
    await mode.click()
    await page.keyboard.press('Escape')
    await expect(dialog).toBeVisible()
    await expect(mode).toBeFocused()
    await expect(description).toBeVisible()
    await dialog.getByRole('button', { name: 'キャンセル' }).click()
    await expect(dialog).not.toBeVisible()
    await trigger.click()
    await expect(mode).toHaveText(/スキップ/)
    await expect(description).toBeVisible()
    await mode.click()
    await page.getByRole('option', { name: '追加（既存データを残す）' }).click()
    await expect(description).not.toBeVisible()
    await mode.click()
    await page.getByRole('option', { name: /スキップ/ }).click()
    await expect(description).toBeInViewport({ ratio: 1 })
    await expect(dialog.getByRole('button', { name: /コピーする/ })).toBeInViewport({ ratio: 1 })
    await page.screenshot({ path: testInfo.outputPath('skip-rules.png'), fullPage: true })
    await dialog.getByRole('button', { name: 'キャンセル' }).click()
  })
}

