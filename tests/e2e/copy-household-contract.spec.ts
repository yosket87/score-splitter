test('種類別の一部選択からキーボードで全選択・全解除を切り替える', async ({ page }, testInfo) => {
  await page.goto('/2026/03')
  await page.getByRole('button', { name: /前月からコピー/ }).click()
  const dialog = page.getByRole('dialog')
  const incomeGroup = dialog.getByRole('checkbox', { name: /^収入/ })
  await expect(incomeGroup).toBeChecked()
  await dialog.getByRole('checkbox', { name: '副業を選択' }).uncheck()
  await expect(incomeGroup).toBeChecked({ indeterminate: true })
  await page.screenshot({ path: testInfo.outputPath('partial-selection.png'), fullPage: true })
  await incomeGroup.focus()
  await page.keyboard.press('Space')
  await expect(incomeGroup).toBeChecked()
  await expect(dialog.getByRole('checkbox', { name: '副業を選択' })).toBeChecked()
  await page.keyboard.press('Space')
  await expect(incomeGroup).not.toBeChecked()
  await expect(dialog.getByRole('checkbox', { name: '副業を選択' })).not.toBeChecked()
  await expect(dialog.getByRole('checkbox', { name: '食費を選択' })).toBeChecked()
  await dialog.getByRole('button', { name: 'キャンセル' }).click()
  await page.getByRole('button', { name: /前月からコピー/ }).click()
  await expect(incomeGroup).toBeChecked()
})

test('項目別コピーモードを中断・再選択・再表示してからコピーできる', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/2026/03')
  const openDialog = page.getByRole('button', { name: /前月からコピー/ })
  // SSRではdesktop用triggerのため、mobileのDrawerへの切替完了を待つ。
  await expect(openDialog).toHaveAttribute('data-slot', 'drawer-trigger')
  await openDialog.click()
  const dialog = page.getByRole('dialog')
  const itemMode = dialog.getByRole('combobox', { name: '副業のコピーモード' })
  await expect(itemMode).toHaveText('金額込み')
  await itemMode.click()
  await expect(page.getByRole('listbox')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('listbox')).not.toBeVisible()
  await expect(dialog).toBeVisible()
  await expect(itemMode).toBeFocused()
  await expect(itemMode).toHaveText('金額込み')
  await itemMode.press('ArrowDown')
  await page.getByRole('option', { name: '項目名のみ' }).click()
  await expect(itemMode).toHaveText('項目名のみ')
  await expect(dialog.getByRole('combobox', { name: '食費のコピーモード' })).toHaveText('金額込み')
  await dialog.getByRole('checkbox', { name: '副業を選択' }).uncheck()
  await expect(itemMode).not.toBeVisible()
  await dialog.getByRole('checkbox', { name: '副業を選択' }).check()
  await expect(itemMode).toHaveText('金額込み')
  await dialog.getByRole('button', { name: 'キャンセル' }).click()
  await openDialog.click()
  await expect(itemMode).toHaveText('金額込み')
  await itemMode.click()
  await page.getByRole('option', { name: '項目名のみ' }).click()
  await page.screenshot({ path: testInfo.outputPath('item-copy-mode.png'), fullPage: true })
  await dialog.getByRole('button', { name: /コピーする/ }).click()
  await expect(dialog).not.toBeVisible()
  const income = page.locator('[data-section="income"]')
  await expect(income.getByText('副業', { exact: true })).toBeVisible()
  // 既存のlabelOnly契約では、正の整数制約を保つため収入は1円でコピーする。
  const copiedItem = income.locator('[data-testid="item-row"]').filter({ hasText: '副業' })
  await expect(copiedItem).toContainText('+¥1')
})
